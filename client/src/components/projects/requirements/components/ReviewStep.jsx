import {
  ArrowRight,
  Check,
  CheckCircle2,
  Edit3,
  Plus,
  Save,
  Sparkles,
  Trash2,
  X,
} from "lucide-react";

import { useState } from "react";
import StepHeader from "./StepHeader";

const ReviewStep = ({
  tasks = [],
  onContinue,
}) => {
  const [reviewTasks, setReviewTasks] = useState(tasks);
  const [editingId, setEditingId] = useState(null);
  const [editForm, setEditForm] = useState({
    title: "",
    type: "",
    complexity: "",
  });

  const [showAddForm, setShowAddForm] = useState(false);

  const [newTask, setNewTask] = useState({
    title: "",
    type: "Frontend",
    complexity: "Medium",
  });

  const [approved, setApproved] = useState(false);

  const startEditing = (task) => {
    setEditingId(task.id);

    setEditForm({
      title: task.title || "",
      type: task.type || "General",
      complexity: task.complexity || "Medium",
    });
  };

  const cancelEditing = () => {
    setEditingId(null);

    setEditForm({
      title: "",
      type: "",
      complexity: "",
    });
  };

  const saveEditing = (taskId) => {
    setReviewTasks((prev) =>
      prev.map((task) =>
        task.id === taskId
          ? {
              ...task,
              title: editForm.title.trim() || task.title,
              type: editForm.type,
              complexity: editForm.complexity,
            }
          : task
      )
    );

    setEditingId(null);
  };

  const removeTask = (taskId) => {
    setReviewTasks((prev) =>
      prev.filter((task) => task.id !== taskId)
    );

    if (editingId === taskId) {
      cancelEditing();
    }
  };

  const handleAddTask = () => {
    if (!newTask.title.trim()) return;

    const task = {
      id: `TASK-${String(reviewTasks.length + 1).padStart(3, "0")}`,
      title: newTask.title.trim(),
      type: newTask.type,
      complexity: newTask.complexity,
      assignee: "Unassigned",
      status: "Added by Admin",
    };

    setReviewTasks((prev) => [...prev, task]);

    setNewTask({
      title: "",
      type: "Frontend",
      complexity: "Medium",
    });

    setShowAddForm(false);
  };

  const handleApprove = () => {
    setApproved(true);
  };

  const handleContinue = () => {
    if (!approved) return;

    onContinue?.();
  };

  return (
    <div>
      <StepHeader
        eyebrow="Admin Review"
        title="Review and refine the AI plan"
        description="Engino has proposed these tasks. Review the plan, make any necessary changes, and approve it before the tasks are created."
        badge={approved ? "Approved" : "Awaiting Review"}
      />

      <div className="space-y-5">
        {/* AI generated notice */}
        <section className="rounded-2xl border border-primary/20 bg-primary-light p-5">
          <div className="flex items-start gap-3">
            <Sparkles
              size={19}
              className="mt-0.5 shrink-0 text-primary"
            />

            <div>
              <h2 className="text-sm font-semibold text-text-primary">
                AI-generated plan
              </h2>

              <p className="mt-1 text-sm leading-6 text-text-secondary">
                These tasks were generated by Engino based on the
                requirement and clarification answers. You have full
                control over the final plan.
              </p>
            </div>
          </div>
        </section>

        {/* Approved state */}
        {approved && (
          <section className="rounded-2xl border border-success/20 bg-success/10 p-5">
            <div className="flex items-start gap-3">
              <CheckCircle2
                size={20}
                className="mt-0.5 shrink-0 text-success"
              />

              <div>
                <h2 className="text-sm font-semibold text-text-primary">
                  Plan approved
                </h2>

                <p className="mt-1 text-sm leading-6 text-text-secondary">
                  The reviewed plan is ready to be converted into
                  actual project tasks.
                </p>
              </div>
            </div>
          </section>
        )}

        {/* Task review */}
        <section className="rounded-2xl border border-border bg-background p-6 shadow-sm">
          <div className="mb-5 flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
            <div>
              <h2 className="text-base font-semibold text-text-primary">
                Tasks to be created
              </h2>

              <p className="mt-1 text-sm text-text-secondary">
                Modify the AI suggestions before approving them.
              </p>
            </div>

            <button
              type="button"
              onClick={() => setShowAddForm((prev) => !prev)}
              className="inline-flex w-fit items-center gap-2 rounded-xl border border-border bg-background px-3.5 py-2 text-sm font-semibold text-text-primary transition hover:bg-surface"
            >
              <Plus size={16} />
              Add Task
            </button>
          </div>

          {/* Add task */}
          {showAddForm && (
            <div className="mb-5 rounded-xl border border-primary/20 bg-primary-light p-5">
              <div className="mb-4 flex items-center justify-between">
                <div>
                  <h3 className="text-sm font-semibold text-text-primary">
                    Add a task
                  </h3>

                  <p className="mt-1 text-xs text-text-secondary">
                    Add work that the AI missed.
                  </p>
                </div>

                <button
                  type="button"
                  onClick={() => setShowAddForm(false)}
                  className="rounded-lg p-1.5 text-text-secondary hover:bg-background hover:text-text-primary"
                >
                  <X size={17} />
                </button>
              </div>

              <div className="grid gap-4 md:grid-cols-[1fr_160px_160px_auto]">
                <input
                  type="text"
                  value={newTask.title}
                  onChange={(event) =>
                    setNewTask((prev) => ({
                      ...prev,
                      title: event.target.value,
                    }))
                  }
                  placeholder="Task title"
                  className="rounded-xl border border-border bg-background px-3.5 py-2.5 text-sm text-text-primary outline-none placeholder:text-text-secondary/70 focus:border-primary focus:ring-2 focus:ring-primary/10"
                />

                <select
                  value={newTask.type}
                  onChange={(event) =>
                    setNewTask((prev) => ({
                      ...prev,
                      type: event.target.value,
                    }))
                  }
                  className="rounded-xl border border-border bg-background px-3.5 py-2.5 text-sm text-text-primary outline-none focus:border-primary"
                >
                  <option>Frontend</option>
                  <option>Backend</option>
                  <option>Full Stack</option>
                  <option>QA</option>
                  <option>DevOps</option>
                  <option>AI</option>
                </select>

                <select
                  value={newTask.complexity}
                  onChange={(event) =>
                    setNewTask((prev) => ({
                      ...prev,
                      complexity: event.target.value,
                    }))
                  }
                  className="rounded-xl border border-border bg-background px-3.5 py-2.5 text-sm text-text-primary outline-none focus:border-primary"
                >
                  <option>Low</option>
                  <option>Medium</option>
                  <option>High</option>
                </select>

                <button
                  type="button"
                  onClick={handleAddTask}
                  disabled={!newTask.title.trim()}
                  className={`rounded-xl px-4 py-2.5 text-sm font-semibold ${
                    newTask.title.trim()
                      ? "bg-primary text-white hover:bg-primary-dark"
                      : "cursor-not-allowed bg-surface text-text-secondary"
                  }`}
                >
                  Add
                </button>
              </div>
            </div>
          )}

          {/* Task list */}
          <div className="space-y-3">
            {reviewTasks.length > 0 ? (
              reviewTasks.map((task, index) => {
                const isEditing = editingId === task.id;

                return (
                  <div
                    key={task.id}
                    className="rounded-xl border border-border bg-surface p-4"
                  >
                    {isEditing ? (
                      <EditTaskForm
                        form={editForm}
                        setForm={setEditForm}
                        onSave={() => saveEditing(task.id)}
                        onCancel={cancelEditing}
                      />
                    ) : (
                      <TaskReviewRow
                        task={task}
                        index={index}
                        onEdit={() => startEditing(task)}
                        onRemove={() => removeTask(task.id)}
                      />
                    )}
                  </div>
                );
              })
            ) : (
              <div className="rounded-xl bg-surface p-6 text-center">
                <p className="text-sm font-medium text-text-primary">
                  No tasks in the plan.
                </p>

                <p className="mt-1 text-xs text-text-secondary">
                  Add at least one task before approving the plan.
                </p>
              </div>
            )}
          </div>
        </section>

        {/* Review principle */}
        <section className="rounded-2xl border border-border bg-background p-5 shadow-sm">
          <div className="flex items-start gap-3">
            <CheckCircle2
              size={19}
              className="mt-0.5 shrink-0 text-success"
            />

            <div>
              <h3 className="text-sm font-semibold text-text-primary">
                You remain in control
              </h3>

              <p className="mt-1 text-sm leading-6 text-text-secondary">
                Engino proposes the work, but the administrator decides
                what actually enters the project.
              </p>
            </div>
          </div>
        </section>

        {/* Footer */}
        <div className="flex flex-col gap-3 border-t border-border pt-5 sm:flex-row sm:items-center sm:justify-end">
          {!approved ? (
            <button
              type="button"
              disabled={reviewTasks.length === 0}
              onClick={handleApprove}
              className={`inline-flex items-center justify-center gap-2 rounded-xl px-5 py-2.5 text-sm font-semibold transition ${
                reviewTasks.length > 0
                  ? "bg-primary text-white hover:bg-primary-dark"
                  : "cursor-not-allowed bg-surface text-text-secondary"
              }`}
            >
              <Check size={17} />
              Approve Plan
            </button>
          ) : (
            <button
              type="button"
              onClick={handleContinue}
              className="inline-flex items-center gap-2 rounded-xl bg-primary px-5 py-2.5 text-sm font-semibold text-white transition hover:bg-primary-dark"
            >
              Continue to Tasks
              <ArrowRight size={17} />
            </button>
          )}
        </div>
      </div>
    </div>
  );
};

const TaskReviewRow = ({
  task,
  index,
  onEdit,
  onRemove,
}) => {
  return (
    <div className="flex flex-col gap-4 lg:flex-row lg:items-center">
      <div className="flex min-w-0 flex-1 items-start gap-4">
        <div className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg bg-background text-xs font-bold text-text-secondary">
          {String(index + 1).padStart(2, "0")}
        </div>

        <div className="min-w-0">
          <p className="text-sm font-semibold text-text-primary">
            {task.title}
          </p>

          <p className="mt-1 text-xs text-text-secondary">
            {task.id}
          </p>

          <div className="mt-3 flex flex-wrap gap-2">
            <span className="rounded-full bg-background px-2.5 py-1 text-[11px] font-medium text-text-secondary">
              {task.type || "General"}
            </span>

            <span className="rounded-full bg-background px-2.5 py-1 text-[11px] font-medium text-text-secondary">
              {task.complexity || "Not specified"}
            </span>

            <span className="rounded-full bg-background px-2.5 py-1 text-[11px] font-medium text-text-secondary">
              {task.assignee || "Unassigned"}
            </span>
          </div>
        </div>
      </div>

      <div className="flex items-center gap-2 lg:shrink-0">
        <button
          type="button"
          onClick={onEdit}
          className="inline-flex items-center gap-1.5 rounded-lg border border-border bg-background px-3 py-2 text-xs font-semibold text-text-primary transition hover:bg-surface"
        >
          <Edit3 size={14} />
          Edit
        </button>

        <button
          type="button"
          onClick={onRemove}
          className="inline-flex items-center gap-1.5 rounded-lg border border-danger/20 bg-background px-3 py-2 text-xs font-semibold text-danger transition hover:bg-danger/10"
        >
          <Trash2 size={14} />
          Remove
        </button>
      </div>
    </div>
  );
};

const EditTaskForm = ({
  form,
  setForm,
  onSave,
  onCancel,
}) => {
  return (
    <div>
      <div className="mb-4 flex items-center justify-between">
        <div>
          <h3 className="text-sm font-semibold text-text-primary">
            Edit task
          </h3>

          <p className="mt-1 text-xs text-text-secondary">
            Modify the AI-generated task.
          </p>
        </div>

        <button
          type="button"
          onClick={onCancel}
          className="rounded-lg p-1.5 text-text-secondary hover:bg-background hover:text-text-primary"
        >
          <X size={17} />
        </button>
      </div>

      <div className="grid gap-4 md:grid-cols-[1fr_160px_160px_auto]">
        <input
          type="text"
          value={form.title}
          onChange={(event) =>
            setForm((prev) => ({
              ...prev,
              title: event.target.value,
            }))
          }
          className="rounded-xl border border-border bg-background px-3.5 py-2.5 text-sm text-text-primary outline-none focus:border-primary focus:ring-2 focus:ring-primary/10"
        />

        <select
          value={form.type}
          onChange={(event) =>
            setForm((prev) => ({
              ...prev,
              type: event.target.value,
            }))
          }
          className="rounded-xl border border-border bg-background px-3.5 py-2.5 text-sm text-text-primary outline-none focus:border-primary"
        >
          <option>Frontend</option>
          <option>Backend</option>
          <option>Full Stack</option>
          <option>QA</option>
          <option>DevOps</option>
          <option>AI</option>
        </select>

        <select
          value={form.complexity}
          onChange={(event) =>
            setForm((prev) => ({
              ...prev,
              complexity: event.target.value,
            }))
          }
          className="rounded-xl border border-border bg-background px-3.5 py-2.5 text-sm text-text-primary outline-none focus:border-primary"
        >
          <option>Low</option>
          <option>Medium</option>
          <option>High</option>
        </select>

        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={onSave}
            className="inline-flex items-center gap-1.5 rounded-lg bg-primary px-3 py-2 text-xs font-semibold text-white hover:bg-primary-dark"
          >
            <Save size={14} />
            Save
          </button>

          <button
            type="button"
            onClick={onCancel}
            className="rounded-lg border border-border bg-background px-3 py-2 text-xs font-semibold text-text-secondary hover:bg-surface"
          >
            Cancel
          </button>
        </div>
      </div>
    </div>
  );
};

export default ReviewStep;